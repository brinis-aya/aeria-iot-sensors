-- Aeria IoT sensors - raw ingestion schema (operational store, not the warehouse)

CREATE TABLE sensor (
    id              VARCHAR(64)  PRIMARY KEY,
    name            VARCHAR(255),
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,
    environment     VARCHAR(32),
    first_seen      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen       TIMESTAMP WITH TIME ZONE NOT NULL,
    message_count   BIGINT NOT NULL DEFAULT 0,
    rejected_count  BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE measurement (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id    VARCHAR(64) NOT NULL REFERENCES sensor(id),
    measured_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    pm25         DOUBLE PRECISION,
    pm10         DOUBLE PRECISION,
    no2          DOUBLE PRECISION,
    o3           DOUBLE PRECISION,
    temperature  DOUBLE PRECISION,
    humidity     DOUBLE PRECISION,
    battery      DOUBLE PRECISION,
    CONSTRAINT uq_measurement_sensor_time UNIQUE (sensor_id, measured_at)
);

CREATE INDEX idx_measurement_time ON measurement (measured_at);
